"""Raccolte di commenti e nomi umani per gli attacchi T1.3(b) e T1.4 (SPEC §12; decisioni
dell'utente del 16 ottobre 2026, ADR-012).

Fonti: funzioni di CodeSearchNet **train** (Python, Java, JavaScript) e funzioni C++ dei repository
del bucket ``attack_pools`` della partizione di The Stack. Sono riferimenti ausiliari, mai dati di
valutazione.

Gli **stessi filtri** valgono per i quattro linguaggi, con il conteggio dopo ciascuno:

- funzioni generate o minificate: riga più lunga di 200 caratteri o marcatori (``@generated``,
  ``auto-generated``, ``generated by``, ``do not edit``); funzioni che non si analizzano;
- commenti (solo quelli dentro le funzioni, una riga sola):
  ``multiline`` → ``length`` (3-120 caratteri) → ``license`` (copyright, licenze, SPDX) →
  ``generated`` → ``directive`` (direttive di tool: ``noqa``, ``eslint``, ``NOLINT``, ``type:``,
  ``fmt:``…, che cambierebbero il comportamento dei tool) → ``code`` (codice commentato: molti
  simboli ``;{}()=<>[]``, fine con ``;`` o graffe, inizio da istruzione) → ``non_english``
  (caratteri non ASCII o meno del 60% di lettere) → ``duplicate``;
- nomi (parametri e variabili locali): ``pattern`` (identificatore ASCII senza ``$``) →
  ``length`` (2-30) → ``reserved`` (parole chiave, builtin, dunder) → ``rare`` (meno di 2
  occorrenze nel corpus) → ``duplicate``.

Ogni raccolta tiene al più ``max_items`` voci, campionate con
``derive_seed(global_seed, "sample", dataset, language, "attack_pools")``.
"""

from __future__ import annotations

import ast
import random
import re
from collections import Counter
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from typing import Any

from pydantic import BaseModel, ConfigDict

from bench.attacks.t1.common import reserved_names
from bench.attacks.t1.rename import _declared
from bench.domain.enums import Language
from bench.lang.functions import outermost_functions, parse_standalone
from bench.lang.parsers import COMMENT_TYPES, ParserService, iter_nodes

MAX_LINE_CHARS = 200
COMMENT_MIN, COMMENT_MAX = 3, 120
NAME_MIN, NAME_MAX = 2, 30
MIN_LETTER_FRACTION = 0.6
MIN_NAME_COUNT = 2
MAX_CODE_CHAR_FRACTION = 0.1

_GENERATED = re.compile(
    r"@generated|auto-?generated|autogenerated|generated by|do not edit|code generator", re.I
)
_LICENSE = re.compile(
    r"copyright|\blicen[cs]e|spdx|all rights reserved|permission is hereby granted|\(c\)\s*\d", re.I
)
_DIRECTIVE = re.compile(
    r"noqa|\btype:\s|pylint:|pyright:|mypy:|eslint|jshint|jslint|istanbul|prettier-ignore|"
    r"clang-format|clang-tidy|nolint|\bfmt:\s|@ts-|#\s*pragma|\bpragma\b|#?region\b|nosec|"
    r"sourcemappingurl|coverage:|iwyu|lgtm|codecov|@flow|@jsx|@license|@preserve",
    re.I,
)
_CODE_START = re.compile(
    r"^(if|for|while|return|import|from|def|class|var|let|const|int|long|double|float|bool|"
    r"public|private|protected|static|void|auto|std::|#include|print|console\.|System\.)\b"
)
_CODE_CHARS = set(";{}()=<>[]")
_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_COMMENT_MARKERS = re.compile(r"^(#+|//+|/\*+)|(\*+/)$")

COMMENT_FILTERS = (
    "multiline", "length", "license", "generated", "directive", "code", "non_english", "duplicate",
)  # fmt: skip
NAME_FILTERS = ("pattern", "length", "reserved", "rare", "duplicate")


class AttackPool(BaseModel):
    """Raccolta di un linguaggio (``data/attack_pools/<lang>.json``)."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    language: Language
    source: str
    comments: list[str]
    names: list[str]
    stats: dict[str, Any]


@dataclass
class PoolBuilder:
    """Accumula commenti e nomi delle funzioni di un linguaggio, con i conteggi dei filtri."""

    language: Language
    parsers: ParserService
    functions: Counter[str] = field(default_factory=Counter)
    comments: list[str] = field(default_factory=list)
    comment_drops: Counter[str] = field(default_factory=Counter)
    name_counts: Counter[str] = field(default_factory=Counter)
    name_drops: Counter[str] = field(default_factory=Counter)
    raw_comments: int = 0
    raw_names: int = 0

    def add_function(self, code: str) -> None:
        """Commenti e nomi di una funzione isolata (scartata se generata o non analizzabile)."""
        self.functions["seen"] += 1
        if max(
            (len(line) for line in code.splitlines()), default=0
        ) > MAX_LINE_CHARS or _GENERATED.search(code):
            self.functions["dropped_generated_or_minified"] += 1
            return
        lang = self.language
        wrapper = parse_standalone(code, lang, self.parsers)
        if wrapper is None:
            self.functions["dropped_parse_error"] += 1
            return
        self.functions["kept"] += 1
        source = wrapper[0] + code + wrapper[1]
        root = self.parsers.parse(source, lang).root_node
        functions = outermost_functions(root, lang)
        for node in (n for fn in functions for n in iter_nodes(fn)):
            if node.type in COMMENT_TYPES and node.text is not None:
                self.raw_comments += 1
                self._comment(node.text.decode("utf-8", errors="replace"))
        names = _python_names(source) if lang is Language.PYTHON else [
            n.text.decode("utf-8") for fn in functions for n in _declared(fn, lang)
            if n.text is not None
        ]  # fmt: skip
        for name in set(names):  # un'occorrenza per funzione
            self.raw_names += 1
            self._name(name)

    def _comment(self, raw: str) -> None:
        drop = comment_drop_reason(raw)
        if drop is not None:
            self.comment_drops[drop] += 1
            return
        self.comments.append(clean_comment(raw))

    def _name(self, name: str) -> None:
        if not _NAME.match(name):
            self.name_drops["pattern"] += 1
        elif not NAME_MIN <= len(name) <= NAME_MAX:
            self.name_drops["length"] += 1
        elif name in reserved_names(self.language) or (
            name.startswith("__") and name.endswith("__")
        ):
            self.name_drops["reserved"] += 1
        else:
            self.name_counts[name] += 1

    def build(self, source: str, seed: int, max_items: int) -> AttackPool:
        """Deduplica, scarta i nomi rari e campiona al più ``max_items`` voci per lista."""
        comments: list[str] = []
        seen: set[str] = set()
        for text in self.comments:
            if text in seen:
                self.comment_drops["duplicate"] += 1
                continue
            seen.add(text)
            comments.append(text)
        names = []
        for name, count in sorted(self.name_counts.items()):
            if count < MIN_NAME_COUNT:
                self.name_drops["rare"] += count
            else:
                self.name_drops["duplicate"] += count - 1
                names.append(name)
        rng = random.Random(seed)
        kept_comments = sorted(rng.sample(sorted(comments), min(max_items, len(comments))))
        kept_names = sorted(rng.sample(names, min(max_items, len(names))))
        stats = {
            "functions": dict(self.functions),
            "comments": _filter_table(self.raw_comments, self.comment_drops, COMMENT_FILTERS)
            | {"available": len(comments), "kept": len(kept_comments)},
            "names": _filter_table(self.raw_names, self.name_drops, NAME_FILTERS)
            | {"available": len(names), "kept": len(kept_names)},
            "max_items": max_items,
        }
        return AttackPool(
            language=self.language,
            source=source,
            comments=kept_comments,
            names=kept_names,
            stats=stats,
        )


def _filter_table(raw: int, drops: Counter[str], order: Iterable[str]) -> dict[str, Any]:
    """Voci rimaste dopo ciascun filtro, nell'ordine di applicazione."""
    left = raw
    after: dict[str, int] = {}
    for name in order:
        left -= drops.get(name, 0)
        after[name] = left
    return {"raw": raw, "dropped": {k: int(drops.get(k, 0)) for k in order}, "left_after": after}


def clean_comment(raw: str) -> str:
    """Testo del commento senza marcatori (``#``, ``//``, ``/* */``) e spazi agli estremi."""
    text = raw.strip()
    previous = None
    while previous != text:
        previous = text
        text = _COMMENT_MARKERS.sub("", text).strip()
    return " ".join(text.split())


def _is_code(text: str) -> bool:
    """Codice commentato: molti simboli di codice, fine con ``;`` o graffe, inizio da istruzione."""
    code_chars = sum(c in _CODE_CHARS for c in text)
    return (
        code_chars / len(text) > MAX_CODE_CHAR_FRACTION
        or text.endswith((";", "{", "}"))
        or bool(_CODE_START.match(text) and code_chars > 0)
    )


def _non_english(text: str) -> bool:
    letters = sum(c.isalpha() for c in text)
    return not text.isascii() or letters / len(text) < MIN_LETTER_FRACTION


def comment_drop_reason(raw: str) -> str | None:
    """Primo filtro che scarta il commento (``None`` se resta)."""
    if "\n" in raw.strip():
        return "multiline"
    text = clean_comment(raw)
    if not COMMENT_MIN <= len(text) <= COMMENT_MAX:
        return "length"
    checks: tuple[tuple[str, Callable[[str], bool]], ...] = (
        ("license", lambda t: bool(_LICENSE.search(t))),
        ("generated", lambda t: bool(_GENERATED.search(t))),
        ("directive", lambda t: bool(_DIRECTIVE.search(t))),
        ("code", _is_code),
        ("non_english", _non_english),
    )
    return next((name for name, check in checks if check(text)), None)


def _python_names(code: str) -> list[str]:
    """Parametri e nomi assegnati dentro le funzioni Python."""
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return []
    out: list[str] = []
    for fn in ast.walk(tree):
        if not isinstance(fn, ast.FunctionDef | ast.AsyncFunctionDef):
            continue
        args = fn.args
        out.extend(a.arg for a in [*args.posonlyargs, *args.args, *args.kwonlyargs])
        out.extend(a.arg for a in (args.vararg, args.kwarg) if a is not None)
        out.extend(
            n.id for n in ast.walk(fn) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store)
        )
    return out
