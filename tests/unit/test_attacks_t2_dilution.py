def test_collisions_with_file_builtins_and_each_other() -> None:
    pool = ["def candidate(a):\n    b = a\n    return b\n",
            "def candidate_ext1(a):\n    b = a\n    return b\n",
            "def sorted(a):\n    b = list(a)\n    return b\n",
            "def math(a):\n    b = a\n    return b\n"]  # fmt: skip
    from bench.attacks.t2.dilution import DilutionAttack

    out = DilutionAttack({"n": 4, "position": "before"}).safe_apply(PROGRAM, Language.PYTHON,
                                                                    _ctx(3, pool))  # fmt: skip
    names = out.detail["names"]
    originals = [pool[i].split("(")[0].removeprefix("def ") for i in out.detail["function_ids"]]
    # sorted, math e candidate collidono con il file o i builtin; candidate_ext1 collide solo se
    # candidate è stata rinominata così prima di lei
    assert len(set(names)) == 4 and "sorted_ext1" in names and "math_ext1" in names
    assert not {"candidate", "sorted", "math"} & set(names)
    assert out.detail["n_renamed"] == sum(a != b for a, b in zip(originals, names, strict=True))
    assert all(n == o or n.startswith(o + "_ext") for o, n in zip(originals, names, strict=True))
    namespace: dict[str, Any] = {}
    exec(compile(out.code + TESTS, "<attacked>", "exec"), namespace)
    assert "sorted" not in namespace  # nessuna def copre il builtin


