def test_statuses() -> None:
    attack = _attack(1, "before")
    empty = attack.safe_apply("  \n", Language.PYTHON, _ctx())
    assert empty.status is AttackStatus.NOT_APPLICABLE and empty.detail["reason"] == "empty_code"
    assert attack.safe_apply("int f();", Language.CPP, _ctx()).status is (
        AttackStatus.NOT_APPLICABLE
    )
    bad = attack.safe_apply("def f(:\n", Language.PYTHON, _ctx())
    assert bad.status is AttackStatus.TOOL_ERROR and bad.code == "def f(:\n"
    small = _attack(4, "around").safe_apply(PROGRAM, Language.PYTHON, _ctx(pool=POOL[:2]))
    assert small.status is AttackStatus.TOOL_ERROR and "function_pools" in small.detail["error"]
    # un file con le sole import: le funzioni vanno in coda
    only = dilute("import os\n", ["def f(x):\n    y = x\n    return y\n"], "before",
                  ast.parse("import os\n"))  # fmt: skip
    assert only == "import os\n\n\ndef f(x):\n    y = x\n    return y\n"
    bare = dilute("x = 1", ["def f(x):\n    return x\n"], "before", ast.parse("x = 1"))
    assert bare == "def f(x):\n    return x\n\n\nx = 1\n"


