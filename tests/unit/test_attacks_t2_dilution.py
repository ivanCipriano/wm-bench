@pytest.mark.parametrize(
    ("raw", "reason"),
    [
        ("def f(x):\n    y = x + 1\n    return y\n", None),
        ("    def f(self, x):\n        y = x\n        return y\n", None),  # rientro tolto
        ("def f(x=None, y=-1, z=(1, 'a')):\n    w = x\n    return w\n", None),
        ("def f(x):\n    y = '" + "a" * 210 + "'\n    return y\n", "generated"),
        ("# auto-generated by tool\ndef f(x):\n    y = x\n    return y\n", "generated"),
        ("def f(x):\n    print x\n    return x\n", "parse"),
        ("def f():\n    nonlocal q\n    q = 1\n    return q\n", "parse"),
        ("class A:\n    x = 1\n    y = 2\n", "single_function"),
        ("def f(x):\n    return x\n", "loc"),
        ("def f(x):\n" + "    x += 1\n" * 40 + "    return x\n", "loc"),
        ("def f(x):\n    import os\n    return os.sep\n", "import"),
        ("@cache\ndef f(x):\n    y = x\n    return y\n", "decorator"),
        ("def f(n):\n    if n:\n        return f(n - 1)\n    return 0\n", "recursive"),
        ("def f(x):\n    global G\n    G = x\n    return G\n", "global"),
        ("def f(x: np.ndarray):\n    y = x\n    return y\n", "definition_time"),
        ("def f(x) -> int:\n    y = x\n    return y\n", "definition_time"),
        ("def f(x=DEFAULT):\n    y = x\n    return y\n", "definition_time"),
        ("def f(*, x=len):\n    y = x\n    return y\n", "definition_time"),
    ],
)
def test_drop_reasons(raw: str, reason: str | None) -> None:
    assert drop_reason(clean_function(raw))[0] == reason


def test_lines_of_code_and_clean() -> None:
    raw = '  def f(x):  \r\n\r\n      # c\r\n      """Doc."""\r\n      return x\r\n\n\n'
    code = clean_function(raw)
    assert code == 'def f(x):\n\n    # c\n    """Doc."""\n    return x\n'
    assert lines_of_code(code) == 3


def test_builder_counts_duplicates_and_stops_when_full() -> None:
    ok = "def f(x):\n    y = x\n    return y\n"
    builder = FunctionPoolBuilder(max_functions=2)
    builder.add_all([(ok, "a/r"), (ok, "a/r"), ("def g(x):\n    return x\n", "b/r"),
                     ("def h(x):\n    z = x\n    return z\n", "b/r"),
                     ("def k(x):\n    z = x\n    return z\n", "c/r")])  # fmt: skip
    assert [r["name"] for r in builder.rows] == ["f", "h"]
    assert [r["function_id"] for r in builder.rows] == [0, 1]
    stats = builder.stats()
    assert stats["raw"] == builder.scanned == 4  # la quinta non si esamina: raccolta piena
    assert stats["dropped"]["duplicate"] == 1 and stats["dropped"]["loc"] == 1
    assert list(stats["dropped"]) == list(FUNCTION_FILTERS)
    assert stats["kept"] == 2 and stats["repositories"] == 2


