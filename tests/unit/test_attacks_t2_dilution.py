@pytest.mark.parametrize(
    ("n", "position", "before", "after"),
    [(1, "before", 1, 0), (2, "around", 1, 1), (4, "around", 2, 2)],
)
def test_positions_and_program_unchanged(n: int, position: str, before: int, after: int) -> None:
    out = _attack(n, position).safe_apply(PROGRAM, Language.PYTHON, _ctx())
    assert out.status is AttackStatus.APPLIED
    d = out.detail
    assert d["n_inserted"] == n and d["position"] == position and len(d["names"]) == n
    assert len(set(d["names"])) == n and len(set(d["function_ids"])) == n
    tree = ast.parse(out.code)
    defs = [s.name for s in tree.body if isinstance(s, ast.FunctionDef | ast.AsyncFunctionDef)]
    i = defs.index("candidate")
    assert defs[:i] == d["names"][:before] and defs[i + 1 :] == d["names"][before:]
    assert len(defs) == n + 1
    assert out.code.startswith('"""Module docstring."""\nfrom __future__ import annotations\n')
    assert d["added_loc"] == sum(lines_of_code(POOL[j]) for j in d["function_ids"])
    # le funzioni aggiunte non cambiano il programma (canoniche verdi)
    namespace: dict[str, Any] = {}
    exec(compile(out.code + TESTS, "<attacked>", "exec"), namespace)
    # determinismo: stesso seme, stesso risultato
    again = _attack(n, position).safe_apply(PROGRAM, Language.PYTHON, _ctx())
    assert again.code == out.code and again.detail == out.detail


