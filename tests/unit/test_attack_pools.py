@pytest.mark.parametrize(
    ("raw", "reason"),
    [
        ("# compute the running total", None),
        ("// skip empty lines", None),
        ("/* check the bounds */", None),
        ("/* first line\n   second line */", "multiline"),
        ("# ok", "length"),
        ("# " + "x" * 130, "length"),
        ("# calcola la somma è facile", "non_english"),
        ("# 1234 5678 9012", "non_english"),
        ("// Copyright 2020 Foo Inc.", "license"),
        ("# Licensed under the Apache License", "license"),
        ("// Auto-generated by the build tool", "generated"),
        ("# noqa: E501 long line here", "directive"),
        ("// eslint-disable-next-line no-console", "directive"),
        ("// NOLINT(readability-braces)", "directive"),
        ("# type: ignore because of stubs", "directive"),
        ("// int x = foo(bar);", "code"),
        ("# return helper(value)", "code"),
        ("// TODO: handle negative numbers {", "code"),
    ],
)
def test_comment_filters(raw: str, reason: str | None) -> None:
    assert comment_drop_reason(raw) == reason


def test_clean_comment() -> None:
    assert clean_comment("///  Spaced   out  ") == "Spaced out"
    assert clean_comment("/** doc */") == "doc"
    assert clean_comment("## heading") == "heading"


@pytest.mark.parametrize(
    ("language", "code"),
    [
        ("python", "def f(alpha, beta):\n    # add the inputs\n    gamma = alpha + beta\n"
                   "    return gamma\n"),
        ("java", "int f(int alpha, int beta) {\n  // add the inputs\n  int gamma = alpha + beta;\n"
                 "  return gamma;\n}"),
        ("cpp", "int f(int alpha, int beta) {\n  // add the inputs\n  int gamma = alpha + beta;\n"
                "  return gamma;\n}\n"),
        ("javascript", "function f(alpha, beta) {\n  // add the inputs\n"
                       "  const gamma = alpha + beta;\n  return gamma;\n}"),
    ],
)  # fmt: skip
def test_pool_builder_same_rules_for_all_languages(language: str, code: str) -> None:
    builder = PoolBuilder(Language(language), default_parsers())
    for _ in range(2):
        builder.add_function(code)
    builder.add_function("x" * 250)  # minificato
    pool = builder.build("test", seed=1, max_items=10)
    assert pool.comments == ["add the inputs"]
    assert pool.names == ["alpha", "beta", "gamma"]
    stats = pool.stats
    assert stats["functions"]["dropped_generated_or_minified"] == 1
    assert stats["comments"]["dropped"]["duplicate"] == 1
    assert stats["names"]["left_after"]["duplicate"] == 3
    # Nomi presenti una volta sola nel corpus: scartati.
    once = PoolBuilder(Language(language), default_parsers())
    once.add_function(code)
    assert once.build("test", seed=1, max_items=10).names == []


@pytest.fixture
def tiny(cfg: ExperimentConfig, local_root: Path) -> ExperimentConfig:
    build_tiny_datasets(local_root / "datasets")
    return rebuild(tiny_config(cfg), stage="attack_pools", languages=["python", "java", "cpp",
                                                                     "javascript"])  # fmt: skip


def test_attack_pools_stage(tiny: ExperimentConfig) -> None:
    facade = BenchmarkFacade(tiny)
    assert facade.run_stage("attack_pools").ran == 4
    for language in ("python", "java", "cpp", "javascript"):
        ref = attack_pool_ref(language)
        pool = facade.store.read_model(ref, AttackPool)
        assert "y0" in pool.names  # nomi locali delle funzioni sintetiche
        assert "x" not in pool.names  # troppo corto
        extra = facade.store.read_manifest(ref).extra  # type: ignore[union-attr]
        assert extra["stats"]["functions"]["kept"] > 0
    cpp = facade.store.read_manifest(attack_pool_ref("cpp")).extra  # type: ignore[union-attr]
    partition = cpp["thestack_partition"]
    assert set(partition) == {"l3_test", "l1_test", "dev", "attack_pools"}
    assert sum(b["files"] for b in partition.values()) == 2 * STACK_FILES
    assert cpp["sampled_functions"] == partition["attack_pools"]["functions"]
